import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson';
const STEP = 2.6;
const LAT_TOP = 84;
const LAT_BOTTOM = -58;
const WIDTH = 1000;
const HEIGHT = 466;
const OUTPUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../src/data/worldDots.ts',
);

function insideRing(point, ring) {
  const [x, y] = point;
  let inside = false;

  for (let index = 0, previous = ring.length - 1; index < ring.length; previous = index, index += 1) {
    const [xi, yi] = ring[index];
    const [xj, yj] = ring[previous];

    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }

  return inside;
}

function insidePolygon(point, rings) {
  if (!insideRing(point, rings[0])) return false;
  for (let index = 1; index < rings.length; index += 1) {
    if (insideRing(point, rings[index])) return false;
  }
  return true;
}

function polygonsFor(feature) {
  const { type, coordinates } = feature.geometry;
  if (type === 'Polygon') return [coordinates];
  if (type === 'MultiPolygon') return coordinates;
  return [];
}

async function main() {
  const response = await fetch(SOURCE, {
    headers: { 'user-agent': 'tay737-portfolio/1.0 (+https://tay737.github.io)' },
    signal: AbortSignal.timeout(30_000),
  });

  if (!response.ok) {
    throw new Error(`Natural Earth returned HTTP ${response.status}`);
  }

  const land = await response.json();
  const polygons = land.features.flatMap(polygonsFor);
  const dots = [];

  for (let lat = LAT_TOP; lat >= LAT_BOTTOM; lat -= STEP) {
    for (let lon = -180; lon <= 180; lon += STEP) {
      if (!polygons.some((rings) => insidePolygon([lon, lat], rings))) continue;

      const x = ((lon + 180) / 360) * WIDTH;
      const y = ((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * HEIGHT;
      dots.push([Number(x.toFixed(1)), Number(y.toFixed(1))]);
    }
  }

  await mkdir(dirname(OUTPUT), { recursive: true });
  await writeFile(
    OUTPUT,
    [
      '/* Generated by scripts/generate-world-dots.mjs from Natural Earth 110m land. */',
      `/* Equirectangular: longitude -180..180 maps to x 0..${WIDTH}, latitude ${LAT_TOP}..${LAT_BOTTOM} maps to y 0..${HEIGHT}. */`,
      'export const WORLD_DOTS: ReadonlyArray<readonly [number, number]> = [',
      ...dots.map(([x, y]) => `  [${x}, ${y}],`),
      '];',
      '',
    ].join('\n'),
  );

  console.log(`World dots: ${dots.length} points written.`);
}

main().catch((error) => {
  console.error(`World dots: ${error.message}`);
  process.exitCode = 1;
});
